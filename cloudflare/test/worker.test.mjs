// End-to-end check of the Worker against a running `wrangler dev --local` (URL in WORKER_URL, default http://localhost:8787).
// The admin password for the test is "Test-Passw0rd-xyz" (the hash is in .dev.vars, made by test/hash.mjs).
const URL_ = process.env.WORKER_URL || 'http://localhost:8787';
const SITE = 'https://devopsdevopshaim-wq.github.io';
const RUN = Date.now();
const PW = 'Test-Passw0rd-xyz', ADMIN = 'devopsdevopshaim@gmail.com';
let bad = 0;
const check = (n, ok, x) => { if (!ok) { bad++; console.error('FAIL', n, x === undefined ? '' : JSON.stringify(x)); } else console.log('ok  ', n); };
async function call(b, { origin = SITE, ip = '10.1.1.1' } = {}) {
  const r = await fetch(URL_ + '/hasadna-auth', { method: 'POST', headers: { ...(origin ? { Origin: origin } : {}), 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams(b) });
  return { code: r.status, body: await r.json().catch(() => null), headers: r.headers };
}
let r = await fetch(URL_ + '/hasadna-auth', { method: 'OPTIONS', headers: { Origin: SITE } });
check('preflight answers for the site', r.status === 204 && r.headers.get('access-control-allow-origin') === SITE);
r = await call({ action: 'info' });
check('info answers', r.body.ok === true && r.headers.get('access-control-allow-origin') === SITE);
r = await call({ action: 'info' }, { origin: 'https://evil.example' });
check('a foreign site is refused', r.code === 403);
r = await call({ action: 'login', email: ADMIN, password: 'wrong-password-123', device: 'a'.repeat(32) });
check('a wrong password is refused', r.body.ok === false && r.code === 401, r);
r = await call({ action: 'login', email: ADMIN, password: PW, device: 'a'.repeat(32) });
check('the admin signs in with the secret password', r.body.ok === true && /^[a-f0-9]{48}$/.test(r.body.token), r);
const token = r.body.token;
r = await call({ action: 'me', token });
check('me', r.body.ok && r.body.role === 'admin');
r = await call({ action: 'clients', token });
check('the clients list is admin only and works', r.body.ok === true);
r = await call({ action: 'clients', token: 'b'.repeat(48) });
check('... and closed without the token', r.code === 403);
// a visitor's tracking, presence, stats, plan, vault
await call({ action: 'track', vid: 'visitor12345', events: JSON.stringify([{ ev: 'view', page: '/portfolio/?x=1', ref: 'https://www.google.com/' }, { ev: 'open', app: 'finance-hub' }]) }, { ip: '10.2.2.2' });
r = await call({ action: 'stats-get', token, days: '7' });
check('stats count the visit', r.body.ok && r.body.days.reduce((a, d) => a + d.v, 0) >= 1 && r.body.apps.some((x) => x[0] === 'finance-hub'));
r = await call({ action: 'presence', token });
check('presence answers', r.body.ok === true && typeof r.body.members === 'number');
r = await call({ action: 'plan-set', token, blob: '{"a":1}' });
r = await call({ action: 'plan-get', token });
check('the plan is kept', r.body.blob === '{"a":1}');
r = await call({ action: 'ai-vault-set', token, blob: '{"gemini":{"key":"k"}}' });
r = await call({ action: 'ai-vault-get', token });
check('the vault is kept', r.body.blob.includes('gemini'));
// a client signs up (no mail provider here: the answer must still come)
r = await call({ action: 'signup', email: `new.${RUN}@example.com`, name: 'לקוח חדש' }, { ip: '10.3.3.3' });
check('sign-up works without a mail provider', r.body.ok === true, r);
r = await call({ action: 'clients', token });
check('the new client is listed', r.body.clients.some((c) => c.email === `new.${RUN}@example.com`));
r = await call({ action: 'clients-import', token, payload: JSON.stringify([{ email: `moved.${RUN}@example.com`, name: 'עבר', sites: ['x'] }]) });
check('clients can be imported from the old server', r.body.ok && r.body.added === 1, r.body);
// the other services that used to be n8n flows
r = await fetch(URL_ + '/hasadna-hubs', { method: 'POST', headers: { Origin: SITE, 'Content-Type': 'text/plain;charset=UTF-8' }, body: JSON.stringify({ action: 'status' }) });
let j = await r.json();
check('the hubs server answers (text/plain body)', j.ok === true && 'ai' in j, j);
r = await fetch(URL_ + '/hasadna-prices', { headers: { Origin: SITE } });
j = await r.json();
check('the price list is read with GET', r.status === 200 && j.ok === true, j);
r = await fetch(URL_ + '/hasadna-lead', { method: 'POST', headers: { Origin: SITE, 'Content-Type': 'application/json' }, body: JSON.stringify({ name: 'בדיקה', phone: '0501234567', service: 'אתר', msg: 'שלום' }) });
j = await r.json();
check('a lead is saved', j.ok === true && j.id, j);
r = await call({ action: 'me', token });
const proof = r.body.biz;
check('the sign-in hands the admin a proof for the leads screen', /^\d{13}\.[a-f0-9]{64}$/.test(proof || ''), r.body);
r = await fetch(URL_ + '/hasadna-admin', { method: 'POST', headers: { Origin: SITE, 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ action: 'list', token: proof, payload: '{}' }) });
j = await r.json();
check('the leads screen lists the lead with that proof', j.ok === true && j.leads.some((l) => l.name === 'בדיקה'), j);
r = await fetch(URL_ + '/hasadna-admin', { method: 'POST', headers: { Origin: SITE, 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ action: 'list', token: 'bad', payload: '{}' }) });
check('... and refuses without it', r.status === 403);
r = await fetch(URL_ + '/hasadna-admin', { method: 'POST', headers: { Origin: SITE, 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ action: 'import', token: proof, payload: JSON.stringify({ leads: [{ id: 'old' + RUN.toString(36), at: '2026-09-01T10:00:00Z', name: 'ליד ישן', phone: '0501111111', status: 'won' }], clicks: { whatsapp: 3 }, prices: { services: {}, offers: [] } }) }) });
j = await r.json();
check('leads from the old server can be imported', j.ok === true && j.leads === 1, j);
r = await fetch(URL_ + '/hasadna-admin', { method: 'POST', headers: { Origin: SITE, 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ action: 'list', token: proof, payload: '{}' }) });
j = await r.json();
check('... and they are listed with their status', j.leads.some((l) => l.name === 'ליד ישן' && l.status === 'won'), j.leads && j.leads.length);
r = await fetch(URL_ + '/hasadna-voice', { method: 'POST', headers: { Origin: SITE, 'Content-Type': 'text/plain' }, body: JSON.stringify({ text: 'שלום' }) });
j = await r.json();
check('the voice server answers (no key here, so it says so)', typeof j.ok === 'boolean', j);
r = await fetch(URL_ + '/comic-draw', { method: 'POST', headers: { Origin: SITE, 'Content-Type': 'text/plain' }, body: JSON.stringify({ mode: 'status' }) });
j = await r.json();
check('the comic server answers', typeof j.ok === 'boolean', j);
r = await fetch(URL_ + '/hasadna-guide', { method: 'POST', headers: { Origin: SITE, 'Content-Type': 'text/plain;charset=UTF-8' }, body: JSON.stringify({ question: 'שלום מאיה', sessionId: 't1', page: '' }) });
j = await r.json();
check('Maya answers (a fallback text when there is no Claude key)', typeof j.answer === 'string' && j.answer.length > 5 && Array.isArray(j.next), j);
r = await fetch(URL_ + '/hasadna-guide', { method: 'POST', headers: { 'Content-Type': 'text/plain' }, body: JSON.stringify({ question: 'x' }) });
j = await r.json();
check('Maya answers with no Origin only through the limit rules', typeof j.answer === 'string', j);
r = await fetch(URL_ + '/hasadna-status?format=json', { headers: { Origin: SITE } });
j = await r.json();
check('the status data is served', r.status === 200 && j.counts && Array.isArray(j.results), j);
r = await fetch(URL_ + '/hasadna-status', { headers: { Origin: SITE } });
check('the status page is HTML with a locked-down policy', r.status === 200 && /text\/html/.test(r.headers.get('content-type')) && /default-src 'none'/.test(r.headers.get('content-security-policy') || ''));
// פריים מגנטים: the business data answers only to a signed-in session from the site, and the owner's content reaches the public site
{
  const fb = async (b, origin = SITE) => { const x = await fetch(URL_ + '/frame-biz', { method: 'POST', headers: { ...(origin ? { Origin: origin } : {}), 'Content-Type': 'text/plain;charset=UTF-8' }, body: JSON.stringify(b) }); return { code: x.status, body: await x.json().catch(() => null) }; };
  let f = await fb({ action: 'all' });
  check('frame: no session, no data', f.code === 401);
  f = await fb({ action: 'all', token }, 'https://evil.example');
  check('frame: a foreign site is refused', f.code === 403);
  f = await fb({ action: 'all', token: 'c'.repeat(48) });
  check('frame: a made-up token is refused', f.code === 401);
  f = await fb({ action: 'site-save', token, site: { name: 'פריים בדיקה ' + RUN, packages: [{ name: 'בסיסי', price: '₪1' }], bank: 'secret-123' } });
  check('frame: the owner publishes content', f.body && f.body.ok, f);
  f = await fb({ action: 'settings-save', token, settings: { account: '998877' } });
  check('frame: the owner keeps bank details', f.body && f.body.ok, f);
  const pub = await (await fetch(URL_ + '/frame-site', { headers: { Origin: SITE } })).json();
  check('frame: the public site reads the content', pub.ok && pub.site && pub.site.name === 'פריים בדיקה ' + RUN);
  check('frame: private fields stay private', !JSON.stringify(pub).includes('secret-123') && !JSON.stringify(pub).includes('998877'));
  f = await fb({ action: 'design-save', token, design: { id: 'test' + RUN, name: 'בדיקה' } });
  f = await fb({ action: 'designs', token });
  check('frame: a signed-in person keeps designs', f.body && f.body.designs.some((x) => x.id === 'test' + RUN));
  // a booking request from the site: no sign-in needed, checked against the calendar, the owner sees it and approves it
  const day = new Date(Date.now() + 90 * 864e5).toISOString().slice(0, 10);
  const book = async (b, origin = SITE) => { const x = await fetch(URL_ + '/frame-book', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'text/plain;charset=UTF-8' }, body: JSON.stringify(b) }); return { code: x.status, body: await x.json().catch(() => null) }; };
  f = await book({ name: 'בדיקה ' + RUN, phone: '050-0000' + String(RUN).slice(-3).padStart(3, '0'), date: day, type: 'wedding', typeName: 'חתונה' });
  check('frame: a booking request is accepted', f.body && f.body.ok && /^R-/.test(f.body.ref), f);
  const rq = f.body && f.body.id;
  check('frame: a booking from a foreign site is refused', (await book({ name: 'x', phone: '0501234567', date: day }, 'https://evil.example')).code === 403);
  f = await fb({ action: 'all', token });
  check('frame: the owner sees the request and the customers', f.body && f.body.requests.some((x) => x.id === rq) && Array.isArray(f.body.accounts), f.body && Object.keys(f.body));
  f = await fb({ action: 'request-decide', token, id: rq, decision: 'approve' });
  check('frame: the owner approves it into a deal', f.body && f.body.ok && f.body.deal && f.body.deal.closed, f);
  const pub2 = await (await fetch(URL_ + '/frame-site', { headers: { Origin: SITE } })).json();
  check('frame: the date shows as taken', pub2.taken.includes(day));
  f = await fb({ action: 'cal-key', token });
  r = await fetch(URL_ + '/frame-cal?k=' + f.body.calKey);
  check('frame: the calendar feed is iCalendar', r.status === 200 && /text\/calendar/.test(r.headers.get('content-type')) && (await r.text()).includes('BEGIN:VEVENT'));
  check('frame: no feed without the key', (await fetch(URL_ + '/frame-cal?k=x')).status === 404);
  if (f.body && f.body.ok) await fb({ action: 'deal-del', token, id: (await fb({ action: 'all', token })).body.deals.find((d) => d.rq === rq).id });
}
// the live event: guests upload with the QR key, a station claims the photo, the gallery serves it with the viewing key
{
  const lv = async (b, origin = SITE) => { const x = await fetch(URL_ + '/frame-live', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'text/plain;charset=UTF-8' }, body: JSON.stringify(b) }); return { code: x.status, body: await x.json().catch(() => null) }; };
  let f = await lv({ action: 'ev-save', token, event: { title: 'בדיקה חיה ' + RUN } });
  check('live: the owner opens an event', f.body && f.body.ok && f.body.event.k, f);
  const ev = f.body.event, img = Buffer.from('fake-jpeg-' + RUN).toString('base64');
  check('live: a foreign site is refused', (await lv({ action: 'guest-info', e: ev.id, k: ev.k }, 'https://evil.example')).code === 403);
  f = await lv({ action: 'guest-up', e: ev.id, k: ev.k, img, name: 'אורח', text: 'מזל טוב' });
  check('live: a guest uploads a photo', f.body && f.body.ok, f);
  const pid = f.body.id;
  f = await lv({ action: 'claim', token, e: ev.id, station: 'בדיקה', max: 3 });
  check('live: the station gets it', f.body && f.body.photos.length === 1 && f.body.photos[0].img === img, f.body && f.body.photos);
  f = await lv({ action: 'feed', e: ev.id, v: ev.v });
  check('live: the gallery lists it', f.body && f.body.photos.some((p) => p.id === pid));
  r = await fetch(URL_ + '/frame-live-img?e=' + ev.id + '&p=' + pid + '&v=' + ev.v);
  check('live: the photo is served with the viewing key', r.status === 200 && Buffer.from(await r.arrayBuffer()).toString('base64') === img);
  check('live: not without it', (await fetch(URL_ + '/frame-live-img?e=' + ev.id + '&p=' + pid + '&v=' + ev.k)).status === 404);
  await lv({ action: 'ev-del', token, e: ev.id });
}
